/**
 * `seo:index` (spec 0006 index.md, Live set): read the slice content folder,
 * validate it, derive the live set and render `live.generated.ts` and
 * `pages.generated.ts`. The jest staleness test calls `buildIndex` on the real
 * folder and compares its output with the files on disk.
 *
 * Node only (`fs`). The middleware never imports this; it imports the
 * generated `live.generated.ts`, which has no imports at all.
 */

import { readdirSync, readFileSync, existsSync } from "node:fs";
import path from "node:path";
import { deriveLiveSet, type LiveSetResult } from "./live-set";
import type { SeoSliceGeneratedPages, SliceContent } from "./types";
import { validateContent } from "./validate";

export const SLICE_CONTENT_DIR = path.resolve(__dirname, "../../content/seo/bangkok");
export const LIVE_FILE = "live.generated.ts";
export const PAGES_FILE = "pages.generated.ts";

const CONTENT_FILE = /^(.+)\.(snapshot|copy|notes)\.json$/;

export function readSliceContent(dir: string = SLICE_CONTENT_DIR): SliceContent {
  const content: SliceContent = { manifest: null, snapshots: {}, copies: {}, notes: {} };
  if (!existsSync(dir)) return content;
  const read = (file: string) => JSON.parse(readFileSync(path.join(dir, file), "utf8"));
  for (const file of readdirSync(dir).sort()) {
    if (file === "manifest.json") {
      content.manifest = read(file);
      continue;
    }
    const m = CONTENT_FILE.exec(file);
    if (!m) continue;
    const [, slug, kind] = m;
    if (kind === "snapshot") content.snapshots[slug] = read(file);
    else if (kind === "copy") content.copies[slug] = read(file);
    else content.notes[slug] = read(file);
  }
  return content;
}

const HEADER = "// Generated by `pnpm --filter @folio/web seo:index`. Do not edit by hand.\n";

export function renderLiveFile(liveSlugs: string[]): string {
  return (
    HEADER +
    "// Slugs only: the edge middleware imports this file (spec 0006 AC-G3).\n\n" +
    `export const LIVE_SLUGS: readonly string[] = ${JSON.stringify(liveSlugs)};\n`
  );
}

/** Every page with files, in manifest order, each snapshot without `eligible` (AC-9). */
export function generatedPages(content: SliceContent): SeoSliceGeneratedPages {
  const pages: SeoSliceGeneratedPages = {};
  for (const { slug } of content.manifest?.pages ?? []) {
    const snapshot = content.snapshots[slug];
    const copy = content.copies[slug] ?? null;
    const notes = content.notes[slug] ?? null;
    if (!snapshot && !copy && !notes) continue;
    let publicSnapshot = null;
    if (snapshot) {
      // eslint-disable-next-line @typescript-eslint/no-unused-vars
      const { eligible, ...rest } = snapshot;
      publicSnapshot = rest;
    }
    pages[slug] = { slug, snapshot: publicSnapshot, copy, notes };
  }
  return pages;
}

export function renderPagesFile(pages: SeoSliceGeneratedPages): string {
  return (
    HEADER +
    "// Every slice page that has files, live or not. Public surfaces take their\n" +
    "// slugs from LIVE_SLUGS, never from these keys (spec 0006 index.md, Files).\n\n" +
    'import type { SeoSliceGeneratedPages } from "@/lib/seo-slice/types";\n\n' +
    `export const SLICE_PAGES: SeoSliceGeneratedPages = ${JSON.stringify(pages, null, 2)};\n`
  );
}

export interface IndexBuild {
  problems: string[];
  live: LiveSetResult;
  files: { [LIVE_FILE]: string; [PAGES_FILE]: string };
}

export function buildIndex(content: SliceContent): IndexBuild {
  const problems = validateContent(content);
  const live = deriveLiveSet(content);
  return {
    problems,
    live,
    files: {
      [LIVE_FILE]: renderLiveFile(live.liveSlugs),
      [PAGES_FILE]: renderPagesFile(generatedPages(content)),
    },
  };
}
